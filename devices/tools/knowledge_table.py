#!/usr/bin/env python3
"""Write a chip's register table from EmbedBenchDeviceData's
knowledge/<chip>.yaml as RegTableSpec (devices/src/regtable_model.h): the
starting point of a model, with power-on contents, widths and which registers
accept writes. What the table cannot say (timing, side effects) stays in the
knowledge file for the hand-written hooks.

    knowledge_table.py --devicedata DIR qmp6988 > qmp6988_table.h

DIR is a clone of EmbedBenchDeviceData (or set EMBEDBENCH_DEVICEDATA).
The data repository keeps the knowledge in a neutral form; this converter,
which knows RegTableSpec, belongs to EmbedBench.
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
from pathlib import Path

import yaml


def ident(chip: str) -> str:
    return "".join(part.capitalize() for part in chip.replace("_", "-").split("-"))


def commit_of(devicedata: Path) -> str:
    try:
        return subprocess.run(["git", "-C", str(devicedata), "rev-parse", "--short", "HEAD"],
                              capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def render(devicedata: Path, chip: str) -> str:
    data = yaml.safe_load((devicedata / "knowledge" / f"{chip}.yaml").read_text(encoding="utf-8"))
    name = ident(chip)
    lines = [f"// Generated by EmbedBench devices/tools/knowledge_table.py from",
             f"// EmbedBenchDeviceData {commit_of(devicedata)} knowledge/{chip}.yaml. Regenerate rather than edit.",
             "#pragma once", "", "#include <regtable_model.h>", ""]
    if not data["registers"]:
        raise SystemExit(f"{chip}: no registers (a command chip); there is no table to write")
    entries = []
    for reg in data["registers"]:
        addr = int(reg["addr"], 16)
        value = bytes.fromhex(reg["reset"])
        if len(value) != reg["width"]:
            raise SystemExit(f"{reg['addr']}: reset is {len(value)} bytes, width {reg['width']}")
        array = f"k{name}Reset_{addr:02X}"
        lines.append(f"// {reg['addr']} {reg.get('name', '')}: {reg['width']} byte(s), {reg['access']}"
                     + (", per specimen" if reg.get("per_specimen") else ""))
        lines.append(f"static const uint8_t {array}[{reg['width']}] = {{"
                     + ", ".join(f"0x{b:02X}" for b in value) + "};")
        flags = []
        if "w" in reg["access"]:
            flags.append("RegTableModel::kWritable")
        if reg.get("volatile"):
            flags.append("RegTableModel::kVolatile")
        entries.append(f"    {{0x{addr:02X}, {reg['width']}, {array}, {' | '.join(flags) or '0'}}},")
    count = len(entries)
    rs = "true" if data.get("addressing", {}).get("repeated_start_required") else "false"
    lines += ["", f"static const RegTableEntry k{name}Entries[{count}] = {{", *entries, "};",
              f"static const RegTableSpec k{name}Spec = {{k{name}Entries, {count}, nullptr, 0, {rs}}};"]
    if data.get("addressing", {}).get("read_auto_increment"):
        lines += ["", "// Reads auto-increment across registers: the table answers at most one",
                  "// register's width, so a model needs an onRead hook for longer reads."]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("chip")
    ap.add_argument("--devicedata", type=Path, default=os.environ.get("EMBEDBENCH_DEVICEDATA"),
                    help="a clone of EmbedBenchDeviceData (default: $EMBEDBENCH_DEVICEDATA)")
    args = ap.parse_args()
    if args.devicedata is None:
        ap.error("--devicedata DIR or EMBEDBENCH_DEVICEDATA is needed")
    sys.stdout.write(render(Path(args.devicedata), args.chip))
    return 0


if __name__ == "__main__":
    sys.exit(main())
